// Writes src/mcp/web/assets.generated.ts: the consent page script and the BIP39 word list as
// strings the Worker serves. Run after editing src/mcp/web/connect.js:
//   pnpm run gen:mcp-assets          (write)
//   pnpm run gen:mcp-assets --check  (fail if out of date; part of `pnpm run typecheck`)
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const script = readFileSync(join(root, "src/mcp/web/connect.js"), "utf8");
const words = readFileSync(join(root, "../packages/MatildeKit/Wordlists/bip39-english.txt"), "utf8").trim();
if (words.split("\n").length !== 2048) throw new Error("bip39 list must have 2048 words");
const hash = (s) => createHash("sha256").update(s).digest("base64");

const out = `// Generated by scripts/gen-mcp-assets.mjs from src/mcp/web/connect.js and
// packages/MatildeKit/Wordlists/bip39-english.txt. Do not edit.

export const CONNECT_JS = ${JSON.stringify(script)};
export const CONNECT_JS_SHA256 = ${JSON.stringify(hash(script))};
export const BIP39_WORDS = ${JSON.stringify(words + "\n")};
`;
const target = join(root, "src/mcp/web/assets.generated.ts");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("src/mcp/web/assets.generated.ts is out of date: run `pnpm run gen:mcp-assets`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
}
