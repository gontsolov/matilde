#!/usr/bin/env python3
"""Generates docs/sync-vectors/v1.json, the shared test vectors for Matilde's sync encryption
(docs/sync-encryption.md). An independent reference implementation of the formats: the Swift tests
(SyncVectorTests) and, later, the TypeScript/web client must reproduce these bytes exactly.

Needs the `cryptography` package. All keys here are fixed test values, never real keys.
"""
import base64
import hashlib
import hmac
import json
import os
import struct

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def fields(*values) -> bytes:
    out = b""
    for value in values:
        raw = str(value).encode()
        out += struct.pack(">H", len(raw)) + raw
    return out


def hkdf(ikm: bytes, salt: bytes, info: str) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=salt, info=info.encode()).derive(ikm)


def padded_length(length: int) -> int:
    needed = length + 1
    if needed <= 32:
        return 32
    e = needed.bit_length() - 1
    s = e.bit_length()
    mask = (1 << (e - s)) - 1
    return (needed + mask) & ~mask


def pad(data: bytes) -> bytes:
    return data + b"\x80" + b"\x00" * (padded_length(len(data)) - len(data) - 1)


def seed(label: str, n: int) -> bytes:
    """Deterministic test bytes."""
    out = b""
    counter = 0
    while len(out) < n:
        out += hashlib.sha256(f"matilde-test-vector/{label}/{counter}".encode()).digest()
        counter += 1
    return out[:n]


def key_check(ak: bytes, key_id: int) -> bytes:
    return hmac.new(ak, fields("matilde/v1/key-check", key_id), hashlib.sha256).digest()


def record(ak, key_id, user_id, record_id, rtype, hlc, deleted, plaintext, salt, nonce):
    aad = fields("matilde/v1", user_id, record_id, rtype, hlc, "1" if deleted else "0", key_id)
    ct = AESGCM(hkdf(ak, salt, "matilde/v1/record")).encrypt(nonce, pad(plaintext), aad)
    return bytes([1]) + struct.pack(">H", key_id) + salt + nonce + ct


def field(ak, key_id, user_id, purpose, subject, value, salt, nonce):
    aad = fields("matilde/v1/field", user_id, purpose, subject, key_id)
    ct = AESGCM(hkdf(ak, salt, "matilde/v1/field")).encrypt(nonce, pad(value), aad)
    return bytes([1]) + struct.pack(">H", key_id) + salt + nonce + ct


def wrap(secret, user_id, slot_id, kind, key_id, plaintext, salt, nonce):
    aad = fields("matilde/v1/slot", user_id, slot_id, kind, key_id)
    ct = AESGCM(hkdf(secret, salt, f"matilde/v1/slot/{kind}")).encrypt(nonce, plaintext, aad)
    return bytes([1]) + salt + nonce + ct


def blob(key, blob_id, plaintext, chunk_size, prefix):
    data = pad(plaintext)
    out = bytes([1]) + struct.pack(">I", chunk_size) + prefix
    chunks = [data[i:i + chunk_size] for i in range(0, len(data), chunk_size)]
    for index, chunk in enumerate(chunks):
        final = "1" if index == len(chunks) - 1 else "0"
        aad = fields("matilde/v1/blob", blob_id, index, final)
        out += AESGCM(key).encrypt(prefix + struct.pack(">I", index), chunk, aad)
    return out


def recovery_code(key: bytes) -> str:
    bits = "".join(f"{b:08b}" for b in key) + f"{hashlib.sha256(key).digest()[0] >> 4:04b}"
    chars = "".join(ALPHABET[int(bits[i:i + 5], 2)] for i in range(0, 260, 5))
    return "-".join(["MTLD"] + [chars[i:i + 4] for i in range(0, 52, 4)])


def main():
    user_id = "6f1c2d3e-4a5b-4c6d-8e7f-90a1b2c3d4e5"
    ak1, ak2 = seed("ak1", 32), seed("ak2", 32)
    recovery = seed("recovery", 32)
    vectors = {
        "comment": "Generated by scripts/sync-vectors.py; format in docs/sync-encryption.md. Test keys only.",
        "userId": user_id,
        "accountKeys": [{"keyId": 1, "key": b64(ak1), "keyCheck": b64(key_check(ak1, 1))},
                        {"keyId": 2, "key": b64(ak2), "keyCheck": b64(key_check(ak2, 2))}],
        "padding": [{"length": n, "padded": padded_length(n)} for n in (0, 1, 30, 31, 32, 100, 1000, 65535, 1_000_000)],
        "records": [],
        "fields": [],
        "slots": [],
        "blobs": [],
        "recoveryCodes": [],
    }
    for index, (key_id, ak, rtype, hlc, text) in enumerate([
        (1, ak1, 2, "1763500000000.00042.0b3c1d2e-3f40-4a51-8b62-7c83d94ea5f6", "# Letter\n\nDear Anna, ünïcødé ✍️"),
        (1, ak1, 1, "1763500000001.00000.0b3c1d2e-3f40-4a51-8b62-7c83d94ea5f6", '{"title":"Letter","goal":"Say thanks"}'),
        (2, ak2, 6, "1763500000002.00001.1c4d2e3f-4051-4b62-8c73-8d94ea5fb607", ""),
        (2, ak2, 2, "1763500000003.00000.1c4d2e3f-4051-4b62-8c73-8d94ea5fb607", "x" * 5000),
    ]):
        record_id = ["a1b2c3d4-e5f6-4a07-8b18-c29d3e4f5a60", "b2c3d4e5-f6a7-4b18-8c29-d3e4f5a6b701",
                     "c3d4e5f6-a7b8-4c29-9d3e-4f5a6b7c8d12", "d4e5f6a7-b8c9-4d3e-8f4a-5b6c7d8e9f23"][index]
        salt, nonce = seed(f"record-salt-{index}", 32), seed(f"record-nonce-{index}", 12)
        plaintext = text.encode()
        vectors["records"].append({
            "keyId": key_id, "recordId": record_id, "type": rtype, "hlc": hlc, "deleted": False,
            "salt": b64(salt), "nonce": b64(nonce), "plaintext": b64(plaintext),
            "envelope": b64(record(ak, key_id, user_id, record_id, rtype, hlc, False, plaintext, salt, nonce)),
        })
    device_id = "0b3c1d2e-3f40-4a51-8b62-7c83d94ea5f6"
    salt, nonce = seed("field-salt", 32), seed("field-nonce", 12)
    vectors["fields"].append({"keyId": 1, "purpose": "device-name", "subject": device_id, "salt": b64(salt), "nonce": b64(nonce),
                              "plaintext": b64("Anna's MacBook".encode()),
                              "envelope": b64(field(ak1, 1, user_id, "device-name", device_id, "Anna's MacBook".encode(), salt, nonce))})
    slot_id = "e5f6a7b8-c9d0-4e1f-8a2b-3c4d5e6f7a80"
    salt, nonce = seed("slot-salt", 32), seed("slot-nonce", 12)
    vectors["slots"].append({"kind": "recovery", "slotId": slot_id, "keyId": 2, "secret": b64(recovery), "salt": b64(salt), "nonce": b64(nonce),
                             "plaintext": b64(ak2), "wrappedKey": b64(wrap(recovery, user_id, slot_id, "recovery", 2, ak2, salt, nonce))})
    slot_id = "f6a7b8c9-d0e1-4f2a-9b3c-4d5e6f7a8b91"
    salt, nonce = seed("slot2-salt", 32), seed("slot2-nonce", 12)
    previous = struct.pack(">H", 1) + ak1
    vectors["slots"].append({"kind": "previous-keys", "slotId": slot_id, "keyId": 2, "secret": b64(ak2), "salt": b64(salt), "nonce": b64(nonce),
                             "plaintext": b64(previous), "wrappedKey": b64(wrap(ak2, user_id, slot_id, "previous-keys", 2, previous, salt, nonce))})
    for index, (size, chunk) in enumerate([(0, 1024), (3000, 1024), (2047, 1024), (9000, 4096)]):
        blob_id = ["17a8b9c0-d1e2-4f3a-8b4c-5d6e7f8a9b02", "28b9c0d1-e2f3-4a4b-9c5d-6e7f8a9b0c13",
                   "39c0d1e2-f3a4-4b5c-8d6e-7f8a9b0c1d24", "4ad1e2f3-a4b5-4c6d-9e7f-8a9b0c1d2e35"][index]
        key, prefix = seed(f"blob-key-{index}", 32), seed(f"blob-prefix-{index}", 8)
        plaintext = seed(f"blob-data-{index}", size)
        vectors["blobs"].append({"blobId": blob_id, "key": b64(key), "chunkSize": chunk, "noncePrefix": b64(prefix),
                                 "plaintextSha256": hashlib.sha256(plaintext).hexdigest(), "plaintextSeed": f"blob-data-{index}", "plaintextLength": size,
                                 "blob": b64(blob(key, blob_id, plaintext, chunk, prefix))})
    for key in (recovery, bytes(32), b"\xff" * 32):
        vectors["recoveryCodes"].append({"key": b64(key), "code": recovery_code(key)})
    path = os.path.join(os.path.dirname(__file__), "..", "docs", "sync-vectors", "v1.json")
    with open(path, "w") as handle:
        json.dump(vectors, handle, indent=2, ensure_ascii=False)
        handle.write("\n")


if __name__ == "__main__":
    main()
